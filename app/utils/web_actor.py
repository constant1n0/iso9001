"""Web adapter helper: the acting principal for the current request."""

from flask_login import current_user

from ..services.actor import Actor


def current_actor() -> Actor:
    """Build the ``Actor`` for the logged-in user, on the ``web`` channel."""
    return Actor.from_user(current_user, channel="web")
